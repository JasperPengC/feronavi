const DICTS: Record<Locale, Dict> = { "zh-CN": zh, "en-US": en };

// detectLocale 在模块初始化时执行，存储键必须先初始化。
const LS_KEY = "feronavi_locale";
let current: Locale = detectLocale();
/**
 * 语言变化要能**触发重渲染** —— 只改模块变量时界面不会跟着变（实测踩到：
 * 英文账号登录后导航仍是中文，因为 setLocale 没有任何订阅者）。
 */
const listeners = new Set<() => void>();
export function subscribeLocale(fn: () => void): () => void {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

/**
 * 未登录/向导场景的语言来源：**localStorage → 浏览器语言**。
 * 登录后以账号偏好（member.locale）为准 —— 两条来源并存，是为了让"还没账号"的人也能选语言：
 * 安装向导第一屏如果只能跟随浏览器语言，英文用户会全程看着中文（那 i18n 等于白做）。
 */
export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(LS_KEY);
    if (saved === "en-US" || saved === "zh-CN") return saved;
  } catch { /* 隐私模式等场景下 localStorage 不可用，忽略 */ }
  if (typeof navigator === "undefined") return "zh-CN";
  return navigator.language?.toLowerCase().startsWith("en") ? "en-US" : "zh-CN";
}

/** 当前语言（供日期/数字格式化使用）—— 日期格式必须跟随界面语言，不能写死 */
export function currentLocale(): string { return current; }

/** 手动选择语言（未登录场景）：持久化到 localStorage，登录后被账号偏好覆盖 */
export function setLocalePreference(locale: Locale): Locale {
  try { localStorage.setItem(LS_KEY, locale); } catch { /* 同上 */ }
  return setLocale(locale);
}

export function getLocale(): Locale {
  return current;
}

export function setLocale(locale: string | null | undefined): Locale {
  const next: Locale = locale === "en-US" ? "en-US" : locale === "zh-CN" ? "zh-CN" : detectLocale();
  if (next !== current) {
    current = next;
    for (const fn of listeners) fn();      // 通知订阅者重渲染
  }
  return next;
}

/** 订阅当前语言：用到 t() 的组件都应调用它，否则切换语言时不会重渲染 */
export function useLocale(): Locale {
  const [loc, setLoc] = useState(current);
  useEffect(() => subscribeLocale(() => setLoc(current)), []);
  return loc;
}

/** 查表：缺键回落中文 + 开发期告警（缺翻译不能白屏） */
export function t(key: string, params?: Record<string, string | number>): string {
  const raw = DICTS[current][key] ?? zh[key];
  if (raw === undefined) {
    // 不用 import.meta.env（本项目未引入 Vite 的类型声明）：缺键一律告警，便于早期发现漏翻译
    console.warn(`[i18n] 缺少文案键：${key}`);
    return key;
  }
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
}

/** 导出字典键集合，供覆盖率脚本核对（框架自检：中英键必须一一对应） */
export function dictKeys(locale: Locale): string[] {
  return Object.keys(DICTS[locale]).sort();
}
