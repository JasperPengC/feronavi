import { defineDataset } from "../types.ts";

const secure = (
  tableName: string,
  columns: readonly string[],
  dateColumns: readonly string[],
  orderBy: readonly string[],
  dependsOn: readonly string[],
  secretColumns: readonly string[],
  options: {
    minimumMode?: "safe" | "full";
    rewrapColumns?: readonly string[];
    safeTransform?: (row: Record<string, unknown>) => Record<string, unknown>;
  } = {},
) =>
  defineDataset({
    name: `security.${tableName}`,
    tableName,
    schemaVersion: 1,
    disposition: "migrate",
    minimumMode: options.minimumMode ?? "full",
    columns,
    dateColumns,
    orderBy,
    dependsOn,
    secretColumns,
    ...options,
  });

