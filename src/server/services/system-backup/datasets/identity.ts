import { defineDataset } from "../types.ts";

const identity = (
  tableName: string,
  columns: readonly string[],
  dateColumns: readonly string[],
  orderBy: readonly string[],
  dependsOn: readonly string[],
  minimumMode: "safe" | "full" = "safe",
) =>
  defineDataset({
    name: `identity.${tableName}`,
    tableName,
    schemaVersion: 1,
    disposition: "migrate",
    minimumMode,
    columns,
    dateColumns,
    orderBy,
    dependsOn,
  });

