import { defineDataset } from "../types.ts";

const content = (
  tableName: string,
  columns: readonly string[],
  dateColumns: readonly string[],
  orderBy: readonly string[],
  dependsOn: readonly string[],
  secretColumns: readonly string[] = [],
  extra: {
    selfReferenceColumns?: readonly string[];
    deferredReferenceColumns?: readonly {
      column: string;
      targetDataset: string;
      targetColumn: string;
    }[];
    safeTransform?: (row: Record<string, unknown>) => Record<string, unknown>;
  } = {},
) =>
  defineDataset({
    name: `content.${tableName}`,
    tableName,
    schemaVersion: 1,
    disposition: "migrate",
    minimumMode: "safe",
    columns,
    dateColumns,
    orderBy,
    dependsOn,
    secretColumns,
    ...extra,
  });

