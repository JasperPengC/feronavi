import assert from "node:assert/strict";
import Fastify from "fastify";
import type { ToolCtx } from "../../src/server/application/capabilities/tools.ts";
assert.match(new URL(process.env.DATABASE_URL ?? "postgres://invalid/").pathname.slice(1), /^feronavi_test_[a-f0-9]{32}$/u);
await (await import("../../src/server/application/bootstrap-business-effects.ts")).bootstrapBusinessEffects();
const { db, sql } = await import("../../src/db/index.ts");
const { member, role, roleAssignment, pagePermission } = await import("../../src/db/schema.ts");
const { eq } = await import("drizzle-orm");
const wiki = await import("../../src/server/services/wiki.service.ts");
const { loadActor } = await import("../../src/server/auth/actor-loader.ts");
const { createProject } = await import("../../src/server/services/project.service.ts");
const code = (name: string) => (e: unknown) => (e as { code?: string }).code === name;
const app = Fastify();
try {
  const [adminRole] = await db.select().from(role).where(eq(role.key, "ADMIN"));
  const [admin, other] = await db.insert(member).values([
    { username: "folders-admin", name: "目录验收", passwordHash: "no-login", status: "ACTIVE" },
    { username: "folders-other", name: "其它成员", passwordHash: "no-login", status: "ACTIVE" },
  ]).returning();
  assert.ok(admin && other && adminRole);
  await db.insert(roleAssignment).values({ memberId: admin.id, roleId: adminRole.id, scopeType: "ORG", scopeId: null });
  const actor = (await loadActor(admin.id))!;
  app.decorate("csrfProtection", async () => {});
  app.addHook("onRequest", async req => { req.actor = actor; });
  app.setErrorHandler((error, _req, reply) => { const e = error as { httpStatus?: number; code?: string }; reply.status(e.httpStatus ?? 500).send({ code: e.code }); });
  await (await import("../../src/server/routes/pages.ts")).registerPageRoutes(app);
  const project = await createProject(actor, { key: "FOLDERS", name: "目录验收" });
  const folder = await wiki.createPage(actor, project.id, { title: "研发资料", kind: "FOLDER" });
  assert.equal(folder.kind, "FOLDER");
  assert.equal(folder.currentRevisionId, null);
  assert.equal((await sql`select count(*)::int as n from page_revision where page_id=${folder.id}`)[0]!.n, 0);
  const structure = await import("../../src/server/services/page-structure.service.ts");
  const organize = async (id: string, patch: { title?: string; parentId?: string | null; archived?: boolean }) => {
    const current = await wiki.getPage(actor, id);
    return structure.organizePage(actor, id, { ...patch, expectedStructureVersion: current.structureVersion });
  };
  const nested = await wiki.createPage(actor, project.id, { title: "设计", kind: "FOLDER", parentId: folder.id });
  const doc = await wiki.createPage(actor, project.id, { title: "目录检索验收", content: "folderneedle 文档内容", parentId: nested.id });
  const old = await wiki.getPage(actor, doc.id);
  const [initialIndex] = await sql`select status, processed, failed from index_job where page_id=${doc.id}`;
  assert.equal(initialIndex?.status, "SUCCEEDED", "首次创建带正文的文档应自动索引");
  assert.equal(initialIndex.failed, 0);
  assert.ok(initialIndex.processed > 0);
  const [indexedRevision] = await sql`select revision_id from page_chunk where page_id=${doc.id} limit 1`;
  assert.equal(indexedRevision?.revision_id, old.currentRevisionId);
  assert.equal((await sql`select count(*)::int as n from index_job where page_id in (${folder.id},${nested.id})`)[0]!.n, 0);
  const empty = await wiki.createPage(actor, project.id, { title: "空白草稿", content: "  " });
  assert.equal((await sql`select count(*)::int as n from index_job where page_id=${empty.id}`)[0]!.n, 0);
  await wiki.deletePage(actor, empty.id);
  let rolledBackId = "";
  await assert.rejects(db.transaction(async () => {
    const rollback = await wiki.createPage(actor, project.id, { title: "回滚创建", content: "不能触发索引" });
    rolledBackId = rollback.id;
    assert.equal((await sql`select count(*)::int as n from index_job where page_id=${rollback.id}`)[0]!.n, 0, "外层事务提交前不能索引");
    throw new Error("rollback-create");
  }), /rollback-create/);
  assert.equal((await sql`select count(*)::int as n from index_job where page_id=${rolledBackId}`)[0]!.n, 0);
  const comments = await import("../../src/server/services/comment.service.ts");
  const attachments = await import("../../src/server/services/attachment.service.ts");
  await organize(doc.id, { parentId: folder.id });
  assert.equal((await wiki.getPage(actor, doc.id)).currentRevisionId, old.currentRevisionId);
  assert.equal((await wiki.getPage(actor, doc.id)).revisionNo, 1);
  await assert.rejects(wiki.updatePage(actor, doc.id, { title: "旧编辑器标题", content: "不能覆盖", expectedRevisionId: old.currentRevisionId!, expectedStructureVersion: old.structureVersion }), code("VERSION_CONFLICT"));
  assert.equal((await wiki.getPage(actor, doc.id)).content, old.content);
  await assert.rejects(structure.organizePage(actor, doc.id, { expectedStructureVersion: old.structureVersion, title: "过期改名" }), code("VERSION_CONFLICT"));
  await assert.rejects(organize(folder.id, { parentId: nested.id }), code("VALIDATION"));
  const alien = await createProject(actor, { key: "ALIENF", name: "其它项目" });
  const alienFolder = await wiki.createPage(actor, alien.id, { title: "其它目录", kind: "FOLDER" });
  await assert.rejects(organize(doc.id, { parentId: alienFolder.id }), code("VALIDATION"));
  const racing = await Promise.allSettled(["改名A", "改名B"].map(title => structure.organizePage(actor, nested.id, { title, expectedStructureVersion: 1 })));
  assert.equal(racing.filter(r => r.status === "fulfilled").length, 1);
  assert.ok(racing.some(r => r.status === "rejected" && code("VERSION_CONFLICT")(r.reason)));
  await assert.rejects(wiki.deletePage(actor, folder.id), code("VALIDATION"));
  await assert.rejects(wiki.updatePage(actor, folder.id, { content: "不能写文件夹正文" }), code("VALIDATION"));
  const rooms = await import("../../src/server/services/collab-room.persistence.ts");
  await assert.rejects(rooms.getOrCreateRoom(actor, "PAGE", folder.id), code("VALIDATION"));
  const knowledge = await import("../../src/server/services/knowledge.service.ts");
  await assert.rejects(knowledge.reindexPage(actor, folder.id, "FULL", { skipEmbedding: true }), code("NOT_FOUND"));
  await knowledge.reindexPage(actor, doc.id, "FULL", { skipEmbedding: true });
  const documentRoom = await rooms.getOrCreateRoom(actor, "PAGE", doc.id);
  const documents = await import("../../src/server/services/collab-document.service.ts");
  const { createContentUpdate } = await import("../../src/server/services/collab-document-core.ts");
  const beforeDraft = await documents.loadDocument(documentRoom.id);
  const draftUpdate = createContentUpdate(beforeDraft.state, "保留尚未发布的协同草稿");
  await documents.applyUpdate({ roomId: documentRoom.id, actorId: actor.memberId, clientId: "folder-test", operationId: "before-archive", updateBase64: Buffer.from(draftUpdate!).toString("base64") });
  const savedDraft = await documents.loadDocument(documentRoom.id);
  const hits = () => knowledge.searchKnowledge(actor, project.id, "folderneedle");
  assert.ok((await hits()).hits.some(h => h.pageId === doc.id));
  assert.equal((await hits()).hits.find(h => h.pageId === doc.id)?.directoryPath, "研发资料");
  await organize(nested.id, { archived: true });
  await organize(folder.id, { archived: true });
  assert.equal((await wiki.getPage(actor, doc.id)).isArchived, true);
  assert.equal((await wiki.listPages(actor, project.id)).length, 0);
  assert.equal((await hits()).hits.length, 0);
  await assert.rejects(wiki.assertPageWritable(actor, doc.id), code("FORBIDDEN"));
  await assert.rejects(wiki.restoreRevision(actor, doc.id, old.currentRevisionId!), code("FORBIDDEN"));
  await assert.rejects(documents.applyUpdate({ roomId: documentRoom.id, actorId: actor.memberId, clientId: "folder-test", operationId: "after-archive", updateBase64: Buffer.from(draftUpdate!).toString("base64") }), code("FORBIDDEN"));
  assert.deepEqual((await documents.loadDocument(documentRoom.id)).state, savedDraft.state);
  await assert.rejects(comments.createComment(actor, { targetType: "PAGE", targetId: doc.id, body: "归档后不可评论" }), code("FORBIDDEN"));
  await assert.rejects(attachments.assertUploadable(actor, "PAGE", doc.id), code("FORBIDDEN"));
  await assert.rejects(wiki.createPage(actor, project.id, { title: "不能写入", parentId: folder.id }), code("VALIDATION"));
  await organize(folder.id, { archived: false });
  assert.equal((await wiki.getPage(actor, nested.id)).isArchived, true, "独立归档的子文件夹保持归档");
  assert.equal((await wiki.getPage(actor, doc.id)).isArchived, false);
  assert.deepEqual((await documents.loadDocument(documentRoom.id)).state, savedDraft.state, "归档恢复不丢失协同草稿");
  assert.ok((await hits()).hits.some(h => h.pageId === doc.id));
  assert.equal((await wiki.getPage(actor, doc.id)).currentRevisionId, old.currentRevisionId);
  const { ALL_TOOLS } = await import("../../src/server/application/capabilities/tools.ts");
  const ctx = { actor, token: { tokenId: "folder-contract", memberId: actor.memberId, tier: "READ_WRITE", projectWhitelist: [project.id] } } as ToolCtx;
  const tool = ALL_TOOLS.find(tool => tool.name === "page.organize")!;
  const current = await wiki.getPage(actor, doc.id);
  const args = { projectId: project.id, pageId: doc.id, title: "MCP整理后的文档", expectedStructureVersion: current.structureVersion, userConfirmed: true };
  await tool.handler(ctx, args);
  await assert.rejects(tool.handler(ctx, args), code("VERSION_CONFLICT"));
  await assert.rejects(tool.handler({ ...ctx, token: { ...ctx.token, tier: "READ_ONLY" } }, args), code("FORBIDDEN"));
  const wrongProject = { ...args, projectId: alien.id };
  await assert.rejects(tool.handler(ctx, wrongProject), code("NOT_FOUND"));
  const rest = await app.inject({ method: "PATCH", url: `/api/v1/pages/${doc.id}/structure`, payload: { expectedStructureVersion: current.structureVersion + 1, parentId: null } });
  assert.equal(rest.statusCode, 200);
  assert.equal(rest.json().parentId, null);
  assert.equal(rest.json().currentRevisionId, old.currentRevisionId);
  assert.equal((await app.inject({ method: "PATCH", url: `/api/v1/pages/${doc.id}/structure`, payload: { parentId: null } })).statusCode, 400);

  const restricted = await wiki.createPage(actor, project.id, { title: "隐藏资料", visibility: "RESTRICTED", parentId: folder.id });
  await db.insert(pagePermission).values({ pageId: restricted.id, principalType: "MEMBER", principalId: other.id, canRead: true, canWrite: true });
  await db.delete(pagePermission).where(eq(pagePermission.principalId, actor.memberId));
  await assert.rejects(organize(folder.id, { archived: true }), code("FORBIDDEN"));
  assert.equal((await wiki.getPage(actor, folder.id)).isArchived, false, "无权限子项不能导致部分归档");
  const hiddenFolder = await wiki.createPage(actor, project.id, { title: "不可泄露祖先", kind: "FOLDER", visibility: "RESTRICTED" });
  const visibleChild = await wiki.createPage(actor, project.id, { title: "可见子文档", content: "visiblechildneedle", parentId: hiddenFolder.id });
  await knowledge.reindexPage(actor, visibleChild.id, "FULL", { skipEmbedding: true });
  await db.delete(pagePermission).where(eq(pagePermission.pageId, hiddenFolder.id));
  assert.equal((await wiki.listPages(actor, project.id)).find(p => p.id === visibleChild.id)?.parentId, null);
  assert.equal((await knowledge.searchKnowledge(actor, project.id, "visiblechildneedle")).hits[0]?.directoryPath, "");
  console.log("document folder contracts passed");
} finally { await app.close(); await sql.end({ timeout: 5 }); }
