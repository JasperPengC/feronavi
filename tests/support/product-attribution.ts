import assert from "node:assert/strict";
import Fastify from "fastify";
import type { ToolCtx } from "../../src/server/application/capabilities/tools.ts";
assert.match(new URL(process.env.DATABASE_URL ?? "postgres://invalid/").pathname.slice(1), /^feronavi_test_[a-f0-9]{32}$/u);
await (await import("../../src/server/application/bootstrap-business-effects.ts")).bootstrapBusinessEffects();
const { db, sql } = await import("../../src/db/index.ts");
const { member, role, roleAssignment } = await import("../../src/db/schema.ts");
const { eq } = await import("drizzle-orm");
const { loadActor } = await import("../../src/server/auth/actor-loader.ts");
const { createProject } = await import("../../src/server/services/project.service.ts");
const products = await import("../../src/server/services/product.service.ts");
const wi = await import("../../src/server/services/work-item.service.ts");
const code = (expected: string) => (e: unknown) => (e as { code?: string }).code === expected;
try {
  const [adminRole] = await db.select().from(role).where(eq(role.key, "ADMIN"));
  const [owner] = await db.insert(member).values({ username: "products-admin", name: "产品验收", passwordHash: "no-login", status: "ACTIVE" }).returning();
  assert.ok(owner && adminRole);
  await db.insert(roleAssignment).values({ memberId: owner.id, roleId: adminRole.id, scopeType: "ORG", scopeId: null });
  const actor = (await loadActor(owner.id))!;
  const one = await createProject(actor, { key: "PRODUCTA", name: "研发项目A" });
  const two = await createProject(actor, { key: "PRODUCTB", name: "研发项目B" });
  const empty = await createProject(actor, { key: "PRODUCTC", name: "未关联项目" });
  let product = await products.createProduct(actor, one.id, { name: "协作产品", description: "持续演进" });
  assert.equal(product.canUnlink, false, "唯一关联项目不能解除");
  assert.equal((await products.listProducts(actor, one.id)).length, 1);
  assert.equal((await products.listProducts(actor, two.id)).length, 0);
  await assert.rejects(products.getProduct(actor, two.id, product.id), code("FORBIDDEN"));
  const requirement = await wi.createWorkItem(actor, one.id, { type: "REQUIREMENT", title: "支持协作", productId: product.id });
  assert.ok(requirement);
  assert.equal(requirement.productId, product.id);
  await assert.rejects(wi.createWorkItem(actor, one.id, { type: "TASK", title: "无效归属", productId: product.id }), code("VALIDATION"));
  await assert.rejects(wi.createWorkItem(actor, two.id, { type: "REQUIREMENT", title: "未关联产品", productId: product.id }), code("FORBIDDEN"));
  const revisionsBefore = (await sql`select count(*)::int as n from requirement_revision where work_item_id=${requirement.id}`)[0]!.n;
  await wi.updateWorkItem(actor, requirement.id, { productId: null, version: requirement.version });
  const detached = await wi.getWorkItem(actor, requirement.id);
  assert.equal(detached.productId, null);
  assert.equal((await sql`select count(*)::int as n from requirement_revision where work_item_id=${requirement.id}`)[0]!.n, revisionsBefore);
  await wi.updateWorkItem(actor, requirement.id, { productId: product.id, version: detached.version });
  product = await products.linkProductProject(actor, one.id, product.id, { targetProjectId: two.id, expectedVersion: product.version });
  assert.equal((await products.listProducts(actor, two.id))[0]?.id, product.id);
  assert.equal((await products.getProduct(actor, two.id, product.id)).canUnlink, true);
  assert.equal((await products.getProduct(actor, one.id, product.id)).canUnlink, false, "引用中的产品不能解除");
  const scoped = { ...actor, grants: actor.grants.map(g => ({ ...g, scopeType: "PROJECT" as const, scopeId: one.id })) };
  await assert.rejects(products.updateProduct(scoped, one.id, product.id, { name: "越权改名", expectedVersion: product.version }), code("FORBIDDEN"));
  assert.equal((await products.getProduct(actor, one.id, product.id, [one.id])).canManage, false);
  await assert.rejects(products.updateProduct(actor, one.id, product.id, { name: "越令牌范围", expectedVersion: product.version }, [one.id]), code("FORBIDDEN"));
  assert.equal(Object.hasOwn(await products.getProduct(actor, one.id, product.id), "projects"), false);
  await assert.rejects(products.unlinkProductProject(actor, one.id, product.id, { expectedVersion: product.version }), code("BLOCKED_BY_PREREQUISITE"));
  const race = await Promise.allSettled(["版本A", "版本B"].map(name => products.updateProduct(actor, one.id, product.id, { name, expectedVersion: product.version })));
  assert.equal(race.filter(r => r.status === "fulfilled").length, 1);
  assert.ok(race.some(r => r.status === "rejected" && code("VERSION_CONFLICT")(r.reason)));
  product = await products.getProduct(actor, one.id, product.id);
  product = await products.updateProduct(actor, one.id, product.id, { archived: true, expectedVersion: product.version });
  assert.equal((await products.listProducts(actor, one.id)).length, 0);
  assert.equal((await products.listProducts(actor, one.id, true)).length, 1);
  await assert.rejects(wi.createWorkItem(actor, two.id, { type: "REQUIREMENT", title: "归档不能挂接", productId: product.id }), code("VALIDATION"));
  const current = await wi.getWorkItem(actor, requirement.id);
  await wi.updateWorkItem(actor, requirement.id, { priority: "HIGH", version: current.version });
  assert.equal((await wi.getWorkItem(actor, requirement.id)).productId, product.id);
  product = await products.updateProduct(actor, one.id, product.id, { archived: false, expectedVersion: product.version });
  await assert.rejects(products.linkProductProject(actor, one.id, product.id, { targetProjectId: empty.id, expectedVersion: product.version }, [one.id,two.id]), code("FORBIDDEN"));
  const unlinked = await products.unlinkProductProject(actor, two.id, product.id, { expectedVersion: product.version });
  assert.equal(unlinked.ok, true);
  await assert.rejects(products.getProduct(actor, two.id, product.id), code("FORBIDDEN"));
  const { ALL_TOOLS } = await import("../../src/server/application/capabilities/tools.ts");
  const context = { actor, token: { tokenId: "product-contract", memberId: actor.memberId, tier: "READ_WRITE", projectWhitelist: [one.id] } } as ToolCtx;
  const create = ALL_TOOLS.find(t => t.name === "product.create")!;
  const input = { projectId: one.id, name: "MCP产品", userConfirmed: true, idempotencyKey: "product-create-once" };
  const first = await create.handler(context, input) as { id: string };
  const replay = await create.handler(context, input) as { id: string };
  assert.equal(first.id, replay.id);
  assert.equal((await sql`select count(*)::int as n from product where name='MCP产品'`)[0]!.n, 1);
  await assert.rejects(create.handler({ ...context, actor: { ...actor, grants: [] } }, input), code("FORBIDDEN"));
  await assert.rejects(create.handler({ ...context, token: { ...context.token, tier: "READ_ONLY" } }, input), code("FORBIDDEN"));
  await assert.rejects(create.handler(context, { ...input, userConfirmed: false }), code("COMMAND_CONFIRMATION_REQUIRED"));
  const linkTool = ALL_TOOLS.find(t => t.name === "product.linkProject")!;
  await assert.rejects(linkTool.handler(context, { projectId: one.id, productId: first.id, targetProjectId: two.id, expectedVersion: 1, userConfirmed: true }), code("FORBIDDEN"));
  await products.linkProductProject(actor, one.id, first.id, {targetProjectId:two.id,expectedVersion:1});
  await assert.rejects(create.handler(context, input), code("FORBIDDEN"));
  const app = Fastify();
  app.decorate("csrfProtection", async () => {});
  app.addHook("onRequest", async req => { req.actor = actor; });
  app.setErrorHandler((error,_req,reply)=>{const e=error as {httpStatus?:number;code?:string};reply.status(e.httpStatus??500).send({code:e.code});});
  await (await import("../../src/server/routes/products.ts")).registerProductRoutes(app);
  try {
    const created = await app.inject({method:"POST",url:`/api/v1/projects/${one.id}/products`,payload:{name:"REST产品"}});
    assert.equal(created.statusCode,201);
    const value=created.json();
    const updated = await app.inject({method:"PATCH",url:`/api/v1/projects/${one.id}/products/${value.id}`,payload:{name:"已改名",expectedVersion:1}});
    assert.equal(updated.statusCode,200);
    assert.equal(updated.json().version,2);
    assert.equal((await app.inject({method:"PATCH",url:`/api/v1/projects/${one.id}/products/${value.id}`,payload:{name:"过期",expectedVersion:1}})).statusCode,409);
    assert.equal((await app.inject({method:"GET",url:`/api/v1/projects/${two.id}/products/${value.id}`})).statusCode,403);
  } finally {await app.close();}
  console.log("product attribution contracts passed");
} finally { await sql.end({timeout:5}); }
