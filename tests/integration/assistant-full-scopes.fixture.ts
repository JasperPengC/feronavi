import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
assert.match(new URL(process.env.DATABASE_URL ?? "postgres://invalid/").pathname, /^\/feronavi_test_[a-f0-9]{32}$/u);
const { db, sql } = await import("../../src/db/index.ts");
const { member, role, roleAssignment, ragMessage } = await import("../../src/db/schema.ts");
const { eq } = await import("drizzle-orm");
const { loadActor } = await import("../../src/server/auth/actor-loader.ts");
const { closeCache } = await import("../../src/server/auth/cache.ts");
const { ensureInitialized } = await import("../../scripts/_test-helpers.ts");
const assistant = await import("../../src/server/services/assistant-tools.ts");
const conversations = await import("../../src/server/services/rag-conversation.service.ts");
const { assertAssistantReplyReadable } = await import("../../src/server/services/assistant-access.ts");
const { BUSINESS_WORKFLOWS } = await import("../../src/server/application/capabilities/intelligence-tools.ts");
try {
  await ensureInitialized();
  const [adminRole] = await db.select().from(role).where(eq(role.key,"ADMIN"));
  const [person] = await db.insert(member).values({username:"full-scope-admin",name:"全范围验收",passwordHash:"no-login",status:"ACTIVE",mustChangePassword:false}).returning();
  await db.insert(roleAssignment).values({memberId:person!.id,roleId:adminRole!.id,scopeType:"ORG"});
  const actor=(await loadActor(person!.id))!;
  const registry = await assistant.assistantRegistry();
  for(const flow of BUSINESS_WORKFLOWS) for(const name of flow.steps) assert.ok(registry.some(t=>t.name===name),`missing ${flow.id}/${name}`);
  const tool=(name:string)=>{const t=registry.find(t=>t.name===name);assert.ok(t,name);return t;};
  const access={actor,projectIds:[] as string[],allowAccount:true,check:async()=>{}};
  const conversation=await conversations.createConversation(actor,{});
  const confirm=async(name:string,args:Record<string,unknown>, scopeAccess=access)=>{
    const action=await assistant.proposeAssistantAction(scopeAccess,tool(name),args);
    const [message]=await db.insert(ragMessage).values({conversationId:conversation.id,requestId:randomUUID(),question:"确认业务修改",status:"completed",reply:{ok:true,answer:"请确认",citations:[],mode:"none",scope:{projectIds:[...scopeAccess.projectIds],projectCount:scopeAccess.projectIds.length},actions:[action]}}).returning();
    const result=await conversations.decideAction(actor,conversation.id,message!.requestId,action.id,"confirm");
    const executed=result.message.reply!.actions![0]!;
    assert.equal(executed.status,"confirmed");assert.ok(executed.result?.observedAt);assert.ok(executed.result?.value);
    const replay=await conversations.decideAction(actor,conversation.id,message!.requestId,action.id,"confirm");
    assert.deepEqual(replay.message.reply!.actions![0]!.result,executed.result);
    return executed;
  };
  const todo=await confirm("todo.create",{title:"无项目的个人待办"});
  assert.equal(todo.projectId,null);assert.equal(todo.scope?.kind,"personal");
  const todos=(await assistant.executeAssistantTool(access,tool("todo.list"),{})).value as {todos:{id:string;title:string}[]};
  const created=todos.todos.find(t=>t.title==="无项目的个人待办");assert.ok(created);
  await confirm("todo.update",{todoId:created.id,done:true});
  await assert.rejects(assistant.proposeAssistantAction({...access,allowAccount:false},tool("todo.create"),{title:"不应跨范围"}),{code:"FORBIDDEN"});
  await assert.rejects(assertAssistantReplyReadable({...actor,memberId:randomUUID()}, {ok:true,answer:"",citations:[],mode:"none",scope:{projectIds:[],projectCount:0},actions:[todo]},[]),{code:"FORBIDDEN"});
  const view = await confirm("savedView.create", { name: "无项目个人视图", viewType: "LIST" });
  assert.equal(view.status, "confirmed");
  await assertAssistantReplyReadable(actor, { ok:true,answer:"",citations:[],mode:"none",scope:{projectIds:[],projectCount:0},actions:[view] }, []);
  await assert.rejects(assertAssistantReplyReadable({...actor,memberId:randomUUID()}, {ok:true,answer:"",citations:[],mode:"none",scope:{projectIds:[],projectCount:0},actions:[view]},[]),{code:"FORBIDDEN"});
  const project=await confirm("project.create",{key:"FULLSCOPE",name:"新建项目复读"});
  const observation=(project.result!.value.observations as {value:{id:string}}[])[0]!;
  assert.ok(observation.value.id);assert.equal(project.projectId,null);
  console.log("PASS empty-project personal create/update confirmation and replay; saved-view reread and owner isolation; new-project reread; 21-workflow catalogue");
} finally { closeCache(); await sql.end({timeout:2}); }
