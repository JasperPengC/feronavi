import "./_env.ts";
/** 一次性测试库：多页索引与增量复用不能让已有知识消失。 */
import assert from "node:assert/strict";
import { eq } from "drizzle-orm";
import { db, sql } from "../src/db/index.ts";
import { member, role, roleAssignment } from "../src/db/schema.ts";
import { loadActor } from "../src/server/auth/actor-loader.ts";
import { createProject } from "../src/server/services/project.service.ts";
import { createPage, getPage, updatePage } from "../src/server/services/wiki.service.ts";
import { reindexPage, searchKnowledge, listPageChunks, activeGeneration } from "../src/server/services/knowledge.service.ts";
import { closeCache } from "../src/server/auth/cache.ts";
assert.match(new URL(process.env.DATABASE_URL!).pathname,/^\/feronavi_test_[a-f0-9]{32}$/u);
try {
 const [m]=await db.insert(member).values({username:"generation-admin",name:"知识索引验收",passwordHash:"no-login",status:"ACTIVE"}).returning();
 const [r]=await db.select().from(role).where(eq(role.key,"ADMIN"));
 await db.insert(roleAssignment).values({memberId:m!.id,roleId:r!.id,scopeType:"ORG",scopeId:null});
 const actor=(await loadActor(m!.id))!;
 const p=await createProject(actor,{key:"GENQA",name:"知识代际回归"});
 const a=await createPage(actor,p.id,{title:"退款规定",content:"# 退款\n退款审核通过后，三个工作日内原路退回。\n\n# 申请资料\n提供订单编号和退款理由。"});
 const b=await createPage(actor,p.id,{title:"发票规定",content:"# 发票\n开票申请后，五个工作日内发送电子发票。"});
 await reindexPage(actor,a!.id,"FULL",{skipEmbedding:true});
 assert.ok((await searchKnowledge(actor,p.id,"退款")).hits.some(h=>h.pageId===a!.id));
 await reindexPage(actor,b!.id,"FULL",{skipEmbedding:true});
 assert.ok((await searchKnowledge(actor,p.id,"退款")).hits.some(h=>h.pageId===a!.id),"第二篇建索引后第一篇仍可检索");
 console.log("PASS 多页索引不会隐藏已有页面");
 const before=await listPageChunks(actor,a!.id);
 const vector=`[${[1,...Array(1023).fill(0)].join(",")}]`;
 await sql`insert into chunk_embedding (chunk_id,model,vector) values (${before.chunks[0]!.id},'fixture-1024',${vector}::vector)`;
 const vectorPreview=await listPageChunks(actor,a!.id);
 assert.equal(vectorPreview.chunks.find(c=>c.id===before.chunks[0]!.id)?.hasVector,true,"已写入向量的切片必须显示向量状态");
 assert.equal(vectorPreview.chunks.find(c=>c.id===before.chunks[1]!.id)?.hasVector,false,"其他切片不能误报已有向量");
 console.log("PASS 切片预览准确区分已有向量和未生成向量");
 const again=await reindexPage(actor,a!.id,"INCREMENTAL",{skipEmbedding:true});
 assert.equal(again.reused,2); assert.equal((await listPageChunks(actor,a!.id)).chunks.length,2);
 assert.ok((await searchKnowledge(actor,p.id,"发票")).hits.some(h=>h.pageId===b!.id));
 console.log("PASS 无变更增量索引保留全部切片与其他页面");
 const current=await getPage(actor,a!.id);
 await updatePage(actor,a!.id,{content:current.content.replace("三个工作日","两个工作日"),expectedRevisionId:current.currentRevisionId!}, { collaborationPublish: true });
 const changed=await reindexPage(actor,a!.id,"INCREMENTAL",{skipEmbedding:true});
 assert.equal(changed.reused,1); assert.equal(changed.total,2);
 const after=await listPageChunks(actor,a!.id);
 assert.equal(after.chunks.length,2); assert.ok(after.chunks.some(c=>c.content.includes("两个工作日")));
 assert.ok(after.chunks.some(c=>c.content.includes("订单编号"))); assert.ok(!after.chunks.some(c=>c.content.includes("三个工作日")));
 console.log("PASS 部分更新同时保留未修改切片并替换旧内容");
 const stableGen=await activeGeneration();
 const staged=await reindexPage(actor,a!.id,"FULL",{skipEmbedding:true,activate:false,generation:stableGen+50});
 assert.equal(await activeGeneration(),stableGen);
 assert.equal((await listPageChunks(actor,a!.id)).chunks.length,2);
 assert.ok((await searchKnowledge(actor,p.id,"退款")).hits.some(h=>h.pageId===a!.id));
 assert.notEqual(staged.generation,before.generation);
 console.log("PASS 未激活的重建不影响正在服务的索引");
 const other=await createProject(actor,{key:"GENOTHER",name:"跨项目索引"});
 const c=await createPage(actor,other.id,{title:"保障规定",content:"# 保修\n质保期为十二个月。"});
 await reindexPage(actor,c!.id,"FULL",{skipEmbedding:true});
 assert.equal((await listPageChunks(actor,a!.id)).generation,changed.generation,"其他页激活后也不能意外启用本页暂存索引");
 assert.ok((await searchKnowledge(actor,p.id,"退款")).hits.some(h=>h.pageId===a!.id));
 assert.ok(!(await searchKnowledge(actor,p.id,"保修")).hits.some(h=>h.pageId===c!.id));
 console.log("PASS 跨项目重建保留原检索，结果维持项目边界");
}finally {await closeCache();await sql.end();}
